-- Jalankan sekali di Supabase SQL Editor: tabel baru + seed sub materi PK dan PM.

-- ===== Sub materi (Subtes > Materi > Sub materi) =====
-- Sub materi = unit belajar (video, PDF, "Tandai selesai"). Soal latihan dan diagnosis tetap di level materi.
-- Kolom materi.video_url dan materi.pdf_url tidak dipakai lagi (dibiarkan agar migrasi aman).
create table if not exists submateri (
  id         bigint generated by default as identity primary key,
  materi_id  bigint  not null references materi (id) on delete cascade,
  nama       text    not null,
  urutan     integer not null default 0,
  video_url  text,                                  -- kosong = tampil "Segera hadir"
  pdf_url    text,
  unique (materi_id, nama)
);
create index if not exists submateri_materi_idx on submateri (materi_id, urutan);

create table if not exists progres_submateri (
  profil_id     uuid   not null references profil (id)    on delete cascade,
  submateri_id  bigint not null references submateri (id) on delete cascade,
  selesai_at    timestamptz not null default now(),
  primary key (profil_id, submateri_id)
);
create index if not exists progres_submateri_idx on progres_submateri (submateri_id);

alter table submateri         enable row level security;
alter table progres_submateri enable row level security;

