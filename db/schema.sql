-- ---------------------------------------------------------------------
-- BAGIAN 1: KONTEN (diisi lewat seed dan skrip impor, bukan oleh pengguna)
-- ---------------------------------------------------------------------

-- 7 subtes UTBK. Jumlah soal dan durasi resmi dipakai oleh Try Out.
create table if not exists subtes (
  id                bigint generated by default as identity primary key,
  nama              text         not null unique,
  kelompok          text         not null
                      check (kelompok in ('Tes Potensi Skolastik', 'Tes Literasi')),
  urutan            integer      not null unique,   -- urutan tampil dan urutan pengerjaan try out
  jumlah_soal_resmi integer      not null check (jumlah_soal_resmi > 0),
  durasi_menit      numeric(5,1) not null check (durasi_menit > 0)   -- boleh desimal: 42,5
);

-- Materi milik tepat satu subtes. Nama boleh sama antar subtes
-- (mis. "Bilangan" di PK dan di PM), tapi unik di dalam satu subtes.
create table if not exists materi (
  id         bigint generated by default as identity primary key,
  subtes_id  bigint  not null references subtes (id) on delete restrict,
  nama       text    not null,
  urutan     integer not null default 0,            -- dari dasar ke lanjut
  video_url  text,                                  -- kosong = tampil "Segera hadir"
  pdf_url    text,
  unique (subtes_id, nama)
);
create index if not exists materi_subtes_idx on materi (subtes_id, urutan);

-- Teks bacaan yang dipakai beberapa soal sekaligus. Versi pertama boleh belum dipakai.
create table if not exists wacana (
  id   bigint generated by default as identity primary key,
  isi  text not null
);

-- Paket try out. "terbit" = false menyembunyikan paket yang soalnya belum lengkap.
create table if not exists try_out (
  id         bigint generated by default as identity primary key,
  judul      text    not null unique,
  deskripsi  text,
  terbit     boolean not null default false,
  dibuat_at  timestamptz not null default now()
);

-- Satu tabel untuk semua soal.
--   try_out_id kosong  -> soal latihan
--   try_out_id terisi  -> soal khusus try out itu (tidak muncul di latihan)
-- Subtes soal didapat lewat materi, jadi tidak ada kolom subtes_id.
-- Kunci jawaban TIDAK ada di sini, tapi di tabel opsi.
create table if not exists soal (
  id          bigint generated by default as identity primary key,
  kode        text unique,                          -- kode stabil agar impor soal bisa diulang tanpa duplikat
  materi_id   bigint not null references materi (id)  on delete restrict,
  wacana_id   bigint          references wacana (id)  on delete restrict,
  try_out_id  bigint          references try_out (id) on delete restrict,
  nomor       integer,                              -- nomor urut di dalam subtes pada try out
  format      text not null default 'pilihan_ganda'
                check (format in ('pilihan_ganda', 'majemuk', 'isian')),
  kesulitan   text not null
                check (kesulitan in ('mudah', 'sedang', 'sulit')),
  pertanyaan  text not null,
  gambar_url  text,
  pembahasan  text,
  dibuat_at   timestamptz not null default now(),
  check (try_out_id is null or nomor is not null)   -- soal try out wajib bernomor
);
-- Postgres tidak membuat indeks otomatis untuk kolom kunci asing, jadi dibuat manual.
create index if not exists soal_latihan_idx on soal (materi_id) where try_out_id is null;
create index if not exists soal_try_out_idx on soal (try_out_id, nomor);
create index if not exists soal_wacana_idx  on soal (wacana_id);

-- Pilihan jawaban. Untuk pilihan ganda: 5 baris, satu is_benar.
-- (Jumlah is_benar per soal diperiksa oleh skrip impor, bukan oleh database,
--  karena format "majemuk" nanti boleh punya lebih dari satu.)
create table if not exists opsi (
  id        bigint generated by default as identity primary key,
  soal_id   bigint  not null references soal (id) on delete cascade,
  label     text    not null,                       -- A, B, C, ...
  isi       text    not null,
  is_benar  boolean not null default false,
  unique (soal_id, label),
  unique (id, soal_id)                              -- dipakai kunci asing gabungan dari tabel jawaban
);

-- Target skor per prodi (estimasi dari data publik).
create table if not exists target_prodi (
  id           bigint generated by default as identity primary key,
  ptn          text         not null,
  prodi        text         not null,
  skor_target  numeric(6,1) not null check (skor_target > 0),
  sumber       text,
  tahun        integer,
  unique (ptn, prodi)
);

-- ---------------------------------------------------------------------
-- BAGIAN 2: PENGGUNA DAN AKTIVITAS
-- ---------------------------------------------------------------------

-- Profil menempel ke akun login Supabase Auth (auth.users).
create table if not exists profil (
  id               uuid primary key references auth.users (id) on delete cascade,
  nama             text,
  target_prodi_id  bigint references target_prodi (id) on delete set null,
  dibuat_at        timestamptz not null default now()
);

-- Satu kali pengerjaan, latihan atau try out.
create table if not exists sesi (
  id          bigint generated by default as identity primary key,
  profil_id   uuid   not null references profil (id) on delete cascade,
  jenis       text   not null check (jenis in ('latihan', 'try_out')),
  try_out_id  bigint references try_out (id) on delete restrict,
  pengaturan  jsonb,                                -- setelan latihan: materi, jumlah, mode, umpan balik
  mulai_at    timestamptz not null default now(),
  selesai_at  timestamptz,                          -- kosong = belum selesai / ditinggalkan
  skor        numeric(6,1),                         -- estimasi total try out
  check ((jenis = 'try_out') = (try_out_id is not null))
);
-- Keputusan "try out sekali per pengguna" dijaga langsung oleh database.
create unique index if not exists sesi_try_out_sekali_idx
  on sesi (profil_id, try_out_id) where jenis = 'try_out';
create index if not exists sesi_riwayat_idx on sesi (profil_id, selesai_at desc);

-- Khusus try out: timer dan skor per subtes.
-- Batas waktu subtes = mulai_at + subtes.durasi_menit.
create table if not exists sesi_subtes (
  sesi_id     bigint not null references sesi (id)   on delete cascade,
  subtes_id   bigint not null references subtes (id) on delete restrict,
  mulai_at    timestamptz not null default now(),
  selesai_at  timestamptz,
  skor        numeric(6,1),
  primary key (sesi_id, subtes_id)
);

-- Jawaban per soal. Latihan: baris dibuat saat Periksa lalu terkunci.
-- Try out: baris dibuat dan diubah selama subtes berjalan.
create table if not exists jawaban (
  id          bigint generated by default as identity primary key,
  sesi_id     bigint not null references sesi (id) on delete cascade,
  soal_id     bigint not null references soal (id) on delete restrict,
  opsi_id     bigint,
  isian       text,                                 -- untuk format isian di masa depan
  ragu        boolean not null default false,
  is_benar    boolean,                              -- latihan: saat Periksa; try out: saat subtes selesai
  dijawab_at  timestamptz not null default now(),
  unique (sesi_id, soal_id),
  -- Kunci asing gabungan: opsi yang dipilih harus milik soal yang sama.
  -- Jika opsi_id kosong (belum memilih), pemeriksaan dilewati.
  foreign key (opsi_id, soal_id) references opsi (id, soal_id)
);
create index if not exists jawaban_soal_idx on jawaban (soal_id);

-- Materi yang sudah ditandai selesai.
create table if not exists progres_materi (
  profil_id   uuid   not null references profil (id)  on delete cascade,
  materi_id   bigint not null references materi (id)  on delete cascade,
  selesai_at  timestamptz not null default now(),
  primary key (profil_id, materi_id)
);
create index if not exists progres_materi_idx on progres_materi (materi_id);

-- ---------------------------------------------------------------------
-- BAGIAN 3: KEAMANAN (Row Level Security)
-- Supabase membuka semua tabel di schema public lewat REST API memakai
-- anon key, dan anon key itu akan ada di tampilan (browser). Tanpa RLS,
-- siapa pun bisa membaca tabel opsi (kunci jawaban!) dan menulis ke tabel
-- lain langsung dari luar API kita.
-- RLS yang aktif tanpa policy = anon dan authenticated ditolak semua.
-- API Express memakai service_role key yang melewati RLS, jadi tetap jalan.
-- ---------------------------------------------------------------------
alter table subtes         enable row level security;
alter table materi         enable row level security;
alter table wacana         enable row level security;
alter table try_out        enable row level security;
alter table soal           enable row level security;
alter table opsi           enable row level security;
alter table target_prodi   enable row level security;
alter table profil         enable row level security;
alter table sesi           enable row level security;
alter table sesi_subtes    enable row level security;
alter table jawaban        enable row level security;
alter table progres_materi enable row level security;

-- ---------------------------------------------------------------------
-- BAGIAN 3b: VIEW STOK SOAL LATIHAN
-- Jumlah soal latihan per materi (try_out_id kosong), supaya API tidak
-- perlu menarik ribuan baris soal hanya untuk menghitung.
-- security_invoker = true: view memakai hak peminta, jadi anon/authenticated
-- tetap terblokir RLS tabel soal. Hanya service_role (API kita) yang melihat isinya.
-- ---------------------------------------------------------------------
create or replace view v_stok_latihan with (security_invoker = true) as
  select materi_id, count(*)::int as jumlah
  from soal
  where try_out_id is null
  group by materi_id;

-- Subtes apa saja yang ada di tiap try out, beserta jumlah soalnya.
-- (Try out boleh mini: hanya memuat sebagian subtes.)
create or replace view v_try_out_subtes with (security_invoker = true) as
  select so.try_out_id, m.subtes_id, count(*)::int as jumlah_soal
  from soal so
  join materi m on m.id = so.materi_id
  where so.try_out_id is not null
  group by so.try_out_id, m.subtes_id;

-- Statistik jawaban per materi untuk satu pengguna (dasar "materi terlemah").
-- Hanya jawaban yang sudah dinilai (is_benar terisi). Latihan dan try out sama-sama dihitung.
-- Hanya service_role (API kita) yang boleh memanggilnya lewat RPC.
create or replace function statistik_materi(p_profil uuid)
returns table (materi_id bigint, benar integer, salah integer)
language sql stable security invoker set search_path = public as $$
  select so.materi_id,
         (count(*) filter (where j.is_benar))::integer,
         (count(*) filter (where not j.is_benar))::integer
  from jawaban j
  join sesi s  on s.id  = j.sesi_id
  join soal so on so.id = j.soal_id
  where s.profil_id = p_profil and j.is_benar is not null
  group by so.materi_id
$$;
revoke all on function statistik_materi(uuid) from public, anon, authenticated;
grant execute on function statistik_materi(uuid) to service_role;

